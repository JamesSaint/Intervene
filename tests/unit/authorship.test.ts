import { describe, expect, it } from 'vitest';
import { attributionProblems } from '../../scripts/check-authorship.mjs';

describe('authorship policy', () => {
  it('rejects tool author and committer identities independently', () => {
    expect(attributionProblems({ authorName: 'Claude', authorEmail: 'noreply@anthropic.com' })).toContain('AI author identity');
    expect(attributionProblems({ committerName: 'claude-code[bot]' })).toContain('AI committer identity');
    expect(attributionProblems({ authorName: 'Claude Opus 5' })).toContain('AI author identity');
  });

  it('rejects AI co-author trailers wherever they occur in a message', () => {
    expect(attributionProblems({ message: 'Fix navigation\nCo-Authored-By: Claude <noreply@anthropic.com>\nMore detail' })).toContain('AI co-author trailer');
  });

  it('rejects formatted credit lines and session attribution in PR descriptions', () => {
    expect(attributionProblems({ message: '_Generated by [Claude Code](https://claude.ai/code/example)_' })).toContain('AI credit line');
    expect(attributionProblems({ message: 'AI-session: abc123' })).toContain('AI session attribution');
  });

  it('preserves human authorship, human co-authors and dependency automation', () => {
    expect(attributionProblems({ authorName: 'James Saint', authorEmail: 'james@jamessaint.com', committerName: 'GitHub', message: 'Co-authored-by: Jane Example <jane@example.com>' })).toEqual([]);
    expect(attributionProblems({ authorName: 'dependabot[bot]', authorEmail: '49699333+dependabot[bot]@users.noreply.github.com', committerName: 'GitHub', message: 'Bump the actions group\nSigned-off-by: dependabot[bot] <support@github.com>' })).toEqual([]);
  });

  it('allows ordinary discussion of tools and AI in technical prose', () => {
    expect(attributionProblems({ authorName: 'James Saint', message: 'Remove Claude attribution\nDocument AI governance and the Codex workflow.' })).toEqual([]);
  });
});
